    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
    String regNo = jTextField1.getText().trim();
    String fullName = jTextField2.getText().trim();
    String year = jTextField3.getText().trim();
    String semester = jTextField4.getText().trim();
    String cgpa = jTextField5.getText().trim();

    // Basic validation
    if (regNo.isEmpty() || fullName.isEmpty() || year.isEmpty() || semester.isEmpty() || cgpa.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all fields.");
        return;
    }

    String error = firstError(
            Validation.validateRegNo(regNo),
            Validation.validateFullName(fullName),
            Validation.validateYear(year),
            Validation.validateSemester(semester),
            Validation.validateCgpa(cgpa));
    if (error != null) {
        JOptionPane.showMessageDialog(this, error);
        return;
    }

    String sql = "INSERT INTO students (reg_no, full_name, current_year, current_semester, cgpa) VALUES (?, ?, ?, ?, ?)";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, regNo);
        pst.setString(2, fullName);
        pst.setInt(3, Integer.parseInt(year));
        pst.setInt(4, Integer.parseInt(semester));
        // DECIMAL(4,2) column: send an exact decimal rather than a lossy float.
        pst.setBigDecimal(5, new java.math.BigDecimal(cgpa));

        int rows = pst.executeUpdate();

        if (rows > 0) {
            JOptionPane.showMessageDialog(this, "Student details saved successfully!");
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");
            jTextField5.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Failed to save student details.");
        }

    } catch (java.sql.SQLIntegrityConstraintViolationException ex) {
        JOptionPane.showMessageDialog(this, "A student with Registration Number '" + regNo + "' already exists.");
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Year, Semester, and CGPA must be numeric values.");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

    private static String firstError(String... errors) {
        for (String e : errors) {
            if (e != null) {
                return e;
            }
        }
        return null;
    }

